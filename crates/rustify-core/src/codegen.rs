    fn gen_classdef(&mut self, stmt: &Stmt) {
        let (name, body) = match stmt {
            Stmt::ClassDef { name, body, .. } => (name, body),
            _ => return,
        };
        let info = match self.env.classes.get(name) {
            Some(i) => i.clone(),
            None => return,
        };

        // Enum-like class: only constants, no methods.
        let has_methods = !info.methods.is_empty();
        if !has_methods && !info.is_dataclass {
            self.w(&format!("pub struct {};", name));
            self.w(&format!("impl {} {{", name));
            self.indent += 1;
            for s in body {
                if let Stmt::Assign { targets, value } = s {
                    if let Expr::Name(n) = &targets[0] {
                        let (c, vty) = self.gen_expr(value).unwrap_or(("0".into(), Ty::Int));
                        let ty = match &vty {
                            Ty::Unknown => self.env.lookup(n).unwrap_or(Ty::Int),
                            other => other.clone(),
                        };
                        match ty {
                            // String enum members become `&'static str`.
                            Ty::Str => {
                                self.w(&format!(
                                    "pub const {}: &str = {};",
                                    rust_ident(n),
                                    c.trim_end_matches(".to_string()")
                                ));
                            }
                            Ty::Bytes => {
                                self.w(&format!(
                                    "pub const {}: &[u8] = {};",
                                    rust_ident(n),
                                    c.trim_end_matches(".to_vec()")
                                ));
                            }
                            _ => {
                                self.w(&format!(
                                    "pub const {}: {} = {};",
                                    rust_ident(n),
                                    ty.rust(),
                                    c
                                ));
                            }
                        }
                    }
                }
            }
            self.indent -= 1;
            self.w("}");
            self.w("");
            return;
        }

        // Dataclass-like class: a struct with fields.
        let mut field_lines = Vec::new();
        for (fname, fty) in &info.fields {
            let default = info
                .field_defaults
                .get(fname)
                .cloned()
                .unwrap_or_else(|| fty.zero());
            field_lines.push(format!("    pub {}: {},", rust_ident(fname), fty.rust()));
            let _ = default;
        }
        self.w(&format!("#[derive(Debug, Clone, PartialEq)]"));
        self.w(&format!("pub struct {} {{", name));
        for fl in &field_lines {
            self.out.push_str(fl);
            self.out.push('\n');
        }
        self.w("}");
        self.w("");

        // Default implementation.
        self.w(&format!("impl Default for {} {{", name));
        self.w("fn default() -> Self {");
        self.indent += 1;
        self.w("Self {");
        self.indent += 1;
        for (fname, fty) in &info.fields {
            let default = info
                .field_defaults
                .get(fname)
                .cloned()
                .unwrap_or_else(|| fty.zero());
            let rendered = self.default_expr(&default, fty);
            self.w(&format!("{}: {},", rust_ident(fname), rendered));
        }
        self.indent -= 1;
        self.w("}");
        self.indent -= 1;
        self.w("}");
        self.w("}");

        // Methods.
        self.w(&format!("impl {} {{", name));
        self.indent += 1;
        let prev_class = self.cur_class.clone();
        self.cur_class = Some(name.clone());
        for s in body {
            if let Stmt::FuncDef { .. } = s {
                self.gen_method(s, &info);
            }
        }
        // Base-class implementations kept for `super()` calls.
        let mut shadowed: Vec<(String, Vec<Param>, Vec<Stmt>)> = Vec::new();
        for (mname, mbody) in &info.method_bodies {
            if let Some(stripped) = mname.strip_prefix("base_") {
                let params = info
                    .method_params
                    .get(mname)
                    .cloned()
                    .unwrap_or_default();
                shadowed.push((stripped.to_string(), params, stripped_doc(mbody)));
            }
        }
        for (mname, params, mbody) in shadowed {
            let stmt = Stmt::FuncDef {
                name: format!("base_{}", mname),
                params,
                returns: None,
                body: mbody,
                decorators: Vec::new(),
            };
            self.gen_method(&stmt, &info);
        }
        self.cur_class = prev_class;
        self.indent -= 1;
        self.w("}");
        self.w("");
    }

    fn default_expr(&mut self, src: &str, ty: &Ty) -> String {
        match ty {
            Ty::Optional(t) => format!("Some({})", self.default_expr(src, t)),
            _ => src.to_string(),
        }
    }

    fn gen_method(&mut self, stmt: &Stmt, info: &ClassInfo) {
        let (name, params, returns, body) = match stmt {
            Stmt::FuncDef {
                name,
                params,
                returns,
                body,
                ..
            } => (name, params, returns, strip_docstring(body)),
            _ => return,
        };
        let sig = match info.methods.get(name) {
            Some(s) => s.clone(),
            None => return,
        };
        let ret_ty = match returns {
            Some(r) => ty_from_annotation(r),
            None => sig.ret.clone(),
        };
        let raises = sig.raises;
        let mutates = body.iter().any(stmt_mutates_self);

        let mut rust_params = vec![if mutates {
            "&mut self".to_string()
        } else {
            "&self".to_string()
        }];
        let mut arg_names = Vec::new();
        let mut param_types = Vec::new();
        let mut_params = info.method_mut_params.get(name).cloned().unwrap_or_default();
        for (p, (pname, pty)) in params.iter().skip(1).zip(sig.params.iter().skip(1)) {
            let pty = match &p.annotation {
                Some(a) => ty_from_annotation(a),
                None => pty.clone(),
            };
            let decl = if mut_params.contains(pname) {
                format!("&mut {}", pty.rust())
            } else if matches!(pty, Ty::Bytes) {
                "&[u8]".to_string()
            } else {
                pty.rust()
            };
            rust_params.push(format!("{}: {}", rust_ident(pname), decl));
            arg_names.push(pname.clone());
            param_types.push(pty);
        }
        let ret_decl = if raises {
            format!("Result<{}, PyErr>", ret_ty.rust())
        } else {
            ret_ty.rust()
        };

        self.w(&format!(
            "pub fn {}({}) -> {} {{",
            rust_ident(name),
            rust_params.join(", "),
            ret_decl
        ));
        self.indent += 1;
        self.declared.push(HashSet::new());
        let prev_module_level = self.module_level;
        self.module_level = false;
        let prev_ret = self.cur_ret.clone();
        let prev_raises = self.cur_raises;
        let prev_in_result = self.in_result_fn;
        self.cur_ret = ret_ty.clone();
        self.cur_raises = raises;
        self.in_result_fn = raises;
        self.env.set("self", Ty::Named(info.name.clone()));

        for (i, pname) in arg_names.iter().enumerate() {
            self.env.set(pname, param_types[i].clone());
        }

        // Python's function scope: hoist every local to the top of the body.
        let mut locals: Vec<(String, Ty)> = Vec::new();
        self.prescan_locals(body, &mut locals);
        self.emit_hoisted(&locals);

        let r = self.gen_block_result(body, &ret_ty, raises);
        self.declared.pop();
        self.cur_ret = prev_ret;
        self.cur_raises = prev_raises;
        self.in_result_fn = prev_in_result;
        self.module_level = prev_module_level;
        self.indent -= 1;

        if body_is_ellipsis(body) {
            self.w("todo!(\"py2rs: abstract method\");");
            self.w("}");
            return;
        }

        match r {
            Ok(()) => {
                if raises {
                    if matches!(ret_ty, Ty::NoneT) {
                        self.w("Ok(())");
                    } else {
                        self.w(&format!("Ok({})", ret_ty.zero()));
                    }
                } else if !matches!(ret_ty, Ty::NoneT) && !body_always_returns(body) {
                    self.w(&format!("{}", ret_ty.zero()));
                }
                self.w("}");
            }
            Err(()) => {
                self.w("todo!(\"py2rs: method not transpiled\")");
                self.w("}");
            }
        }
    }

