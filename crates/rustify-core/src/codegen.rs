/// True when a function body is only the `...` placeholder.
fn body_is_ellipsis(body: &[Stmt]) -> bool {
    body.len() == 1
        && matches!(&body[0], Stmt::ExprStmt(Expr::Name(n)) if n == "...")
}

/// True when a value of this type is not `Copy` and therefore has to be
/// cloned before it can be moved into another value.
fn needs_clone(ty: &Ty) -> bool {
    match ty {
        Ty::Int | Ty::Float | Ty::Bool | Ty::NoneT => false,
        Ty::Optional(inner) => needs_clone(inner),
        _ => true,
    }
}

/// Remove a leading docstring from a statement block.
fn strip_docstring(body: &[Stmt]) -> &[Stmt] {
    match body.first() {
        Some(Stmt::ExprStmt(Expr::Str { .. })) => &body[1..],
        _ => body,
    }
}

/// Like `strip_docstring`, but returns an owned vector.
fn stripped_doc(body: &[Stmt]) -> Vec<Stmt> {
    strip_docstring(body).to_vec()
}

/// True when control cannot fall off the end of the block.
fn body_always_returns(body: &[Stmt]) -> bool {
    match body.last() {
        Some(Stmt::Return(_)) | Some(Stmt::Raise { .. }) => true,
        Some(Stmt::If { body, orelse, .. }) => {
            !orelse.is_empty() && body_always_returns(body) && body_always_returns(orelse)
        }
        Some(Stmt::Try {
            body,
            handlers,
            orelse,
            finalbody,
        }) => {
            body_always_returns(body)
                && handlers.iter().all(|h| body_always_returns(&h.body))
                && (orelse.is_empty() || body_always_returns(orelse))
                && finalbody.is_empty()
        }
        _ => false,
    }
}

fn stmt_has_top_level_return(s: &Stmt) -> bool {    match s {
        Stmt::Return(_) => true,
        Stmt::If { body, orelse, .. } => {
            body.iter().any(stmt_has_top_level_return)
                || orelse.iter().any(stmt_has_top_level_return)
        }
        _ => false,
    }
}

fn stmt_mutates_self(s: &Stmt) -> bool {
    match s {
        Stmt::Assign { targets, .. } => targets.iter().any(target_mutates_self),
        Stmt::AugAssign { target, .. } => target_mutates_self(target),
        Stmt::AnnAssign { target, .. } => target_mutates_self(target),
        Stmt::If { body, orelse, .. } => {
            body.iter().any(stmt_mutates_self) || orelse.iter().any(stmt_mutates_self)
        }
        Stmt::While { body, orelse, .. } => {
            body.iter().any(stmt_mutates_self) || orelse.iter().any(stmt_mutates_self)
        }
        Stmt::For { body, orelse, .. } => {
            body.iter().any(stmt_mutates_self) || orelse.iter().any(stmt_mutates_self)
        }
        Stmt::Try {
            body,
            handlers,
            orelse,
            finalbody,
        } => {
            body.iter().any(stmt_mutates_self)
                || handlers.iter().any(|h| h.body.iter().any(stmt_mutates_self))
                || orelse.iter().any(stmt_mutates_self)
                || finalbody.iter().any(stmt_mutates_self)
        }
        Stmt::With { body, .. } => body.iter().any(stmt_mutates_self),
        _ => false,
    }
}

fn target_mutates_self(t: &Expr) -> bool {
    match t {
        Expr::Attribute { value, .. } => matches!(&**value, Expr::Name(n) if n == "self"),
        Expr::Subscript { value, .. } => matches!(&**value, Expr::Name(n) if n == "self"),
        _ => false,
    }
}

/// Extract the arguments of a `range(...)` call, if the expression is one.
fn range_args(e: &Expr) -> Option<(Expr, Expr, Option<Expr>)> {
    if let Expr::Call { func, args } = e {
        if let Expr::Name(n) = &**func {
            if n == "range" {
                let pos: Vec<&Expr> = args
                    .iter()
                    .filter_map(|a| match a {
                        Arg::Pos(e) => Some(e),
                        _ => None,
                    })
                    .collect();
                return match pos.len() {
                    1 => Some((
                        Expr::Num(NumVal::Int(0)),
                        pos[0].clone(),
                        None,
                    )),
                    2 => Some((pos[0].clone(), pos[1].clone(), None)),
                    3 => Some((pos[0].clone(), pos[1].clone(), Some(pos[2].clone()))),
                    _ => None,
                };
            }
        }
    }
    None
}
